function results = main_realistic_comparison(overrides)
% 五方法共用官方ECL导航、非理想传感器及真实异质时变执行器，仅切换分配器。
if nargin<1, overrides=struct(); end
ca_setup();
base=struct('navigation_mode',"px4_ecl",'plant_model',"shc09_6dof",'measurement_mode',"meng_filtered", ...
    'flight_mode',"position_hold",'initial_position_ned_m',[0;0;-10],'position_reference_ned_m',[0;0;-10], ...
    'duration_s',8,'roll_amplitude_deg',0,'pitch_amplitude_deg',0,'yaw_amplitude_deg',0, ...
    'position_reference_stages',[0,0,0,-10;3,0,0.5,-10;5,0.5,0,-10;7,0,0,-10], ...
    'tau_actual_s',0.001*[24;27;30;33;36;40],'tau_model_s',0.03*ones(6,1), ...
    'actuator_tau_variation_enabled',true,'attitude_noise_std_deg',zeros(3,1), ...
    'output_tag',char("realistic_px4_ecl_"+string(datetime('now','Format','yyyyMMdd_HHmmss'))));
for field=reshape(string(fieldnames(overrides)),1,[]), base.(field)=overrides.(field); end
results=main_comparison(base);
end
