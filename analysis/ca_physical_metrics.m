function metrics = ca_physical_metrics(results)
% 物理状态和气动表覆盖范围单独汇总，不把数值完成等同于模型适用。
rows={};
for method=results.config.methods
    log=results.logs.(method);
    rows(end+1,:)={char(method),max(vecnorm(log.position_ned_m,2,2)), ...
        max(vecnorm(log.velocity_ned_m_s,2,2)),max(vecnorm(log.airspeed_body_m_s,2,2)), ...
        min(log.exit_speed_m_s),max(log.exit_speed_m_s), ...
        min(log.motor_rad_s),max(log.motor_rad_s),sum(log.table_extrapolated), ...
        100*mean(log.table_extrapolated)}; %#ok<AGROW>
end
metrics=cell2table(rows,'VariableNames',{'method','peak_position_norm_m','peak_velocity_norm_m_s', ...
    'peak_airspeed_m_s','min_exit_speed_m_s','max_exit_speed_m_s','min_motor_rad_s','max_motor_rad_s', ...
    'aero_extrapolated_samples','aero_extrapolated_percent'});
end
