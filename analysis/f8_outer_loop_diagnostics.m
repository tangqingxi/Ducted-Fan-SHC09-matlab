function report=f8_outer_loop_diagnostics(log_path,output_path)
% 仅离线分解竖直力缺口与导航偏差；原物理函数用于评价，不向控制器提供真值。
ca_setup();d=load(log_path);L=d.L;c=d.c;m=d.m;r=d.ref;p=m.parameters;
keep=find(r.time_s>=6&r.time_s<=50);keep=keep(1:8:end);n=numel(keep);values=zeros(n,11);
for k=1:n
    i=keep(k);R=ca_euler_rotation(L.euler_rad(i,:)');Rd=ca_euler_rotation(L.desired_euler_rad(i,:)');
    physical=ca_shc09_aerodynamics(R,L.velocity_ned_m_s(i,:)',L.omega_rad_s(i,:)',L.actual_delta_rad(i,:)',L.motor_rad_s(i),m,c);
    force=R*physical.force_body_n;actual_axial=R*[0;0;-p.Duct.k_T0*L.motor_rad_s(i)^2];
    commanded_axial=R*[0;0;-p.Duct.k_T0*L.motor_command_rad_s(i)^2];desired_axial=Rd*[0;0;-p.Duct.k_T0*L.motor_command_rad_s(i)^2];
    az=r.acceleration_ned_m_s2(i,3)+c.position_gain(3)*(r.position_ned_m(i,3)-L.estimated_position_ned_m(i,3)) ...
        +c.velocity_gain(3)*(r.velocity_ned_m_s(i,3)-L.estimated_velocity_ned_m_s(i,3));
    az=min(4,max(-4,az));
    values(k,:)=[r.time_s(i),L.position_ned_m(i,3)-r.position_ned_m(i,3),L.estimated_position_ned_m(i,3)-L.position_ned_m(i,3), ...
        L.estimated_velocity_ned_m_s(i,3),az,(force(3)-actual_axial(3))/m.mass_kg, ...
        (actual_axial(3)-commanded_axial(3))/m.mass_kg,(commanded_axial(3)-desired_axial(3))/m.mass_kg, ...
        force(3)/m.mass_kg+p.g,desired_axial(3)/m.mass_kg+p.g,physical.thrust_n];
end
T=array2table(values,'VariableNames',{'time_s','true_downward_position_error_m','estimated_minus_true_z_m','estimated_velocity_down_m_s', ...
    'vertical_command_acceleration_m_s2','aero_axial_map_gap_down_m_s2','motor_lag_gap_down_m_s2', ...
    'attitude_projection_gap_down_m_s2','physical_down_acceleration_m_s2','nominal_command_down_acceleration_m_s2','physical_axial_thrust_n'});
closure=max(abs(T.physical_down_acceleration_m_s2-(T.nominal_command_down_acceleration_m_s2 ...
    +T.aero_axial_map_gap_down_m_s2+T.motor_lag_gap_down_m_s2+T.attitude_projection_gap_down_m_s2)));
report=struct('log_path',string(log_path),'method',string(L.name),'seed',d.protocol.seed,'diagnostic_sampling_hz',100, ...
    'true_altitude_rms_m',sqrt(mean((L.position_ned_m(r.time_s>=6&r.time_s<=50,3)-r.position_ned_m(r.time_s>=6&r.time_s<=50,3)).^2)), ...
    'mean_true_downward_position_error_m',mean(T.true_downward_position_error_m),'mean_estimated_minus_true_z_m',mean(T.estimated_minus_true_z_m), ...
    'mean_estimated_down_velocity_m_s',mean(T.estimated_velocity_down_m_s),'mean_vertical_command_acceleration_m_s2',mean(T.vertical_command_acceleration_m_s2), ...
    'mean_aero_axial_map_gap_down_m_s2',mean(T.aero_axial_map_gap_down_m_s2),'mean_motor_lag_gap_down_m_s2',mean(T.motor_lag_gap_down_m_s2), ...
    'mean_attitude_projection_gap_down_m_s2',mean(T.attitude_projection_gap_down_m_s2),'force_decomposition_max_closure_error_m_s2',closure, ...
    'max_nominal_command_vs_unclipped_vertical_control_difference_m_s2',max(abs(T.nominal_command_down_acceleration_m_s2-T.vertical_command_acceleration_m_s2)), ...
    'not_a_closed_loop_counterfactual',true,'truth_used_for_offline_evaluation_only',true);
assert(closure<1e-10,'竖直力分解不闭合。');
if nargin>1
    assert(~isfile(output_path),'不覆盖既有外环诊断。');writetable(T,strrep(output_path,'.json','.csv'));
    fid=fopen(output_path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s',jsonencode(report,PrettyPrint=true));
end
disp(report);
end
