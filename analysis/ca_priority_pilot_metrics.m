function metrics = ca_priority_pilot_metrics(results)
% 分开报告无负载、负载稳定、机动及恢复，避免把跟踪代价混成单一名次。
cfg=results.config; t=results.reference.time_s;
windows=[0,2;3,4;4,10;10.5,12]; names=["quiet","loaded_hold","maneuver","recovery"];
rows={};
for w=1:size(windows,1)
    selected=t>=windows(w,1) & t<windows(w,2);
    for method=cfg.methods
        if ~isfield(results.logs,method), continue; end
        log=results.logs.(method);
        position=log.position_ned_m(selected,:)-results.reference.position_ned_m(selected,:);
        yaw=atan2(sin(log.euler_rad(selected,3)-results.reference.euler_rad(selected,3)), ...
            cos(log.euler_rad(selected,3)-results.reference.euler_rad(selected,3)));
        yaw=rad2deg(yaw);
        rate=rad2deg(log.omega_rad_s(selected,:)-log.omega_reference_rad_s(selected,:));
        events=log.pwm_update_time_s>=windows(w,1) & log.pwm_update_time_s<windows(w,2);
        commands=rad2deg(log.pwm_command_rad(events,:)); changes=diff(commands);
        normal=log.mode(selected)==0 & isfinite(log.lambda(selected));
        scaled=normal & log.lambda(selected)<1-1e-6;
        lambda=log.lambda(selected); lambda=lambda(normal);
        if isempty(lambda), minimum=NaN; mean_lambda=NaN; else, minimum=min(lambda); mean_lambda=mean(lambda); end
        rows(end+1,:)={char(method),char(names(w)),sqrt(mean(yaw.^2)),max(abs(yaw)), ...
            sqrt(mean(sum(position.^2,2))),sqrt(mean(position(:,2).^2)),sqrt(mean(position(:,3).^2)), ...
            sqrt(mean(sum(rate.^2,2))),max(abs(rad2deg(log.euler_rad(selected,1:2))),[],'all'), ...
            100*mean(any(abs(commands)>=results.model.command_limit_deg-1e-5,2)), ...
            sqrt(mean(changes.^2,'all')),100*mean(scaled),sum(scaled)/cfg.sample_hz,minimum,mean_lambda, ...
            100*mean(log.mode(selected)==1),100*mean(log.mode(selected)==2), ...
            sum(log.solver_exitflag(selected)<=0),sum(log.solver_rescue(selected)), ...
            100*mean(log.table_extrapolated(selected))}; %#ok<AGROW>
    end
end
metrics=cell2table(rows,'VariableNames',{'method','window','yaw_rmse_deg','yaw_peak_deg', ...
    'position_rmse_m','east_rmse_m','height_rmse_m','rate_control_rmse_deg_s','peak_roll_pitch_deg', ...
    'pwm_saturation_percent','command_step_rms_deg','normal_scaled_percent','normal_scaled_s', ...
    'min_native_lambda','mean_native_lambda','mode1_percent','mode2_percent', ...
    'solver_nonoptimal_count','solver_rescue_count','aero_extrapolated_percent'});
end
