function ca_write_logs(log,ref,folder)
% 分别导出控制计算和PWM下发日志；共同评估预测与算法内部预测分列保存。
data=table(ref.time_s,log.lambda,log.beta,log.mode,log.solve_time_s,log.iterations, ...
    log.solver_exitflag,log.native_residual,log.common_residual,log.priority_distance, ...
    log.native_prediction_available,log.native_horizon_s,log.prediction_delay_s, ...
    'VariableNames',{'time_s','lambda','beta','mode','solve_time_s','iterations','exitflag', ...
    'native_residual','common_residual','priority_distance','native_prediction_available', ...
    'native_horizon_s','wait_s'});
data=[data,columns(log.command_rad,'candidate',true),columns(log.held_command_rad,'held',true), ...
    columns(log.actual_delta_rad,'actual',true),columns(log.estimated_delta_rad,'estimated',true), ...
    columns(log.native_predicted_delta_rad,'native_predicted',true), ...
    columns(log.common_predicted_delta_rad,'common_predicted',true), ...
    columns(log.euler_error_rad,'attitude_error',true),columns(log.v_h,'v_h',false),columns(log.v_c,'v_c',false), ...
    columns(log.disturbance_torque_nm,'disturbance_nm',false)];
data=[data,columns(rad2deg(log.measured_omega_rad_s),'measured_rate_deg_s',false), ...
    columns(log.measured_euler_rad,'measured_euler',true),columns(log.attitude_noise_rad,'attitude_noise',true), ...
    columns(rad2deg(log.gyro_noise_rad_s),'gyro_noise_deg_s',false), ...
    columns(log.measured_alpha_rad_s2,'measured_alpha_rad_s2',false), ...
    columns(log.true_alpha_rad_s2,'true_alpha_rad_s2',false), ...
    columns(log.feedback_delta_rad,'feedback_delta',true)];
if isfield(log,'position_ned_m')
    data=[data,columns(log.position_ned_m,'position_ned_m',false), ...
        columns(log.velocity_ned_m_s,'velocity_ned_m_s',false), ...
        columns(log.airspeed_body_m_s,'airspeed_body_m_s',false), ...
        columns(log.aero_torque_nm,'plant_torque_nm',false), ...
        table(log.motor_rad_s,log.motor_command_rad_s,log.exit_speed_m_s,log.table_extrapolated, ...
        'VariableNames',{'motor_rad_s','motor_command_rad_s','exit_speed_m_s','table_extrapolated'})];
end
if isfield(log,'duct_angle_rad')
    data=[data,table(rad2deg(log.duct_angle_rad),rad2deg(log.wing_angle_rad), ...
        'VariableNames',{'duct_angle_deg','wing_angle_deg'})];
end
if isfield(log,'omega_reference_rad_s')
    data=[data,columns(rad2deg(log.omega_reference_rad_s),'rate_reference_deg_s',false), ...
        columns(log.alpha_reference_rad_s2,'alpha_reference_rad_s2',false)];
end
if isfield(log,'allocation_held_command_rad')
    data=[data,columns(log.allocation_held_command_rad,'allocation_held',true), ...
        columns(log.position_reference_ned_m,'position_reference_ned_m',false)];
end
if isfield(log,'restore_exitflag')
    data=[data,table(log.restore_exitflag,log.restore_iterations,log.restore_effect_error, ...
        'VariableNames',{'restore_exitflag','restore_iterations','restore_effect_error'})];
end
if isfield(log,'actual_tau_s'), data=[data,columns(log.actual_tau_s,'actual_tau_s',false)]; end
if isfield(log,'restore_solver_rescue')
    data=[data,table(log.restore_solver_rescue,'VariableNames',{'restore_solver_rescue'})];
end
if isfield(log,'estimated_position_ned_m')
    data=[data,columns(log.estimated_position_ned_m,'estimated_position_ned_m',false), ...
        columns(log.estimated_velocity_ned_m_s,'estimated_velocity_ned_m_s',false), ...
        columns(log.estimated_gyro_bias_rad_s,'estimated_gyro_bias_rad_s',false), ...
        columns(log.estimated_accelerometer_bias_m_s2,'estimated_accelerometer_bias_m_s2',false), ...
        columns(log.navigation_position_variance_m2,'navigation_position_variance_m2',false), ...
        columns(log.navigation_health,'navigation_health',false),columns(log.navigation_new_aiding,'navigation_new_aiding',false), ...
        columns(log.raw_gyro_rad_s,'raw_gyro_rad_s',false),columns(log.raw_specific_force_m_s2,'raw_specific_force_m_s2',false), ...
        columns(log.gnss_position_ned_m,'gnss_position_ned_m',false), ...
        table(log.navigation_step_time_s,'VariableNames',{'navigation_step_time_s'})];
end
if isfield(log,'moment_model_error_nm')
    data=[data,table(log.moment_model_error_nm,'VariableNames',{'moment_model_error_nm'}), ...
        columns(log.effective_delta_rad,'effective_delta_rad',false), ...
        columns(log.vane_incremental_gain,'vane_incremental_gain',false)];
end
if isfield(log,'low_speed_regularized')
    data=[data,table(log.low_speed_regularized,'VariableNames',{'low_speed_regularized'})];
end
writetable(data,fullfile(folder,'control.csv'),'Encoding','UTF-8');
events=table(log.pwm_update_time_s,log.pwm_source_time_s,log.pwm_prediction_checked, ...
    'VariableNames',{'pwm_time_s','source_time_s','completed_hold'});
events=[events,columns(log.pwm_command_rad,'command',true), ...
    columns(log.pwm_end_predicted_delta_rad,'common_predicted_end',true), ...
    columns(log.pwm_end_actual_delta_rad,'actual_end',true), ...
    columns(log.pwm_end_prediction_error_rad,'common_prediction_error',true)];
writetable(events,fullfile(folder,'pwm.csv'),'Encoding','UTF-8');
if isfield(log,'topic_log'),shc09_write_topic_index(log.topic_log,folder);end
end

function result=columns(values,prefix,angle)
if angle, values=rad2deg(values); prefix=[prefix,'_deg']; end
result=array2table(values,'VariableNames',cellstr(compose('%s_%d',prefix,1:size(values,2))));
end
