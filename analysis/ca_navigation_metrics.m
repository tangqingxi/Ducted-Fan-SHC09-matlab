function metrics = ca_navigation_metrics(results)
% 用真实状态评价导航误差，但性能统计不反向送入控制器或官方EKF。
rows={}; t=results.reference.time_s;
for method=results.config.methods
    log=results.logs.(method);
    if ~isfield(log,'estimated_position_ned_m'), continue; end
    for stage=["whole","after_2s"]
        selected=t<results.config.duration_s;
        if stage=="after_2s", selected=selected & t>=2; end
        if ~any(selected), continue; end
        position=log.position_ned_m(selected,:)-results.reference.position_ned_m(selected,:);
        estimate=log.estimated_position_ned_m(selected,:)-log.position_ned_m(selected,:);
        velocity=log.estimated_velocity_ned_m_s(selected,:)-log.velocity_ned_m_s(selected,:);
        attitude=log.measured_euler_rad(selected,:)-log.euler_rad(selected,:);
        attitude=rad2deg(atan2(sin(attitude),cos(attitude)));
        yaw=rad2deg(atan2(sin(log.euler_rad(selected,3)-results.reference.euler_rad(selected,3)), ...
            cos(log.euler_rad(selected,3)-results.reference.euler_rad(selected,3))));
        delta=rad2deg(log.estimated_delta_rad(selected,:)-log.actual_delta_rad(selected,:));
        health=log.navigation_health(selected,:);
        rows(end+1,:)={char(method),char(stage),sqrt(mean(sum(position.^2,2))),sqrt(mean(yaw.^2)), ...
            sqrt(mean(sum(estimate.^2,2))),sqrt(mean(sum(velocity.^2,2))), ...
            sqrt(mean(sum(attitude.^2,2))),sqrt(mean(delta.^2,'all')), ...
            sum(any(~logical(health(:,1:5)),2)),sum(health(:,6)~=0), ...
            sum(log.solver_exitflag(selected)<=0),sum(log.restore_exitflag(selected)<=0), ...
            sum(log.restore_solver_rescue(selected)),sum(log.table_extrapolated(selected)),100*mean(log.table_extrapolated(selected)), ...
            1e3*median(log.navigation_step_time_s(selected)),1e3*median(log.solve_time_s(selected))}; %#ok<AGROW>
    end
end
metrics=cell2table(rows,'VariableNames',{'method','stage','true_position_tracking_rmse_m','true_yaw_rmse_deg', ...
    'navigation_position_rmse_m','navigation_velocity_rmse_m_s','navigation_euler_vector_rmse_deg', ...
    'estimated_fin_rmse_deg','invalid_navigation_samples','navigation_fault_samples', ...
    'primary_nonoptimal_samples','restore_nonoptimal_samples','restore_rescue_samples','aero_extrapolated_samples', ...
    'aero_extrapolated_percent','navigation_median_ms','allocator_median_ms'});
end
