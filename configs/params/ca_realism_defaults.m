function cfg = ca_realism_defaults(cfg)
% 为旧配置补兼容默认值，新模式必须显式选择，避免重绘旧数据时改变实验含义。
% 旧配置按原导航标志映射，保留旧ECL入口的覆盖语义。
if ~isfield(cfg,'estimator_mode')
    cfg.estimator_mode="ideal";
    if isfield(cfg,'navigation_mode') && string(cfg.navigation_mode)=="px4_ecl",cfg.estimator_mode="px4_ecl";end
end
defaults=struct('gyro_noise_density_dps_sqrtHz',0.004,'gyro_lpf_hz',100, ...
    'gyro_bias_walk_deg_s_sqrt_s',0.01,'lite_seed',72001, ...
    'lite_attitude_kp',2,'lite_attitude_ki',0.05,'lite_position_tau_s',2, ...
    'lite_velocity_tau_s',0.5,'lite_baro_tau_s',2,'lite_gnss_timeout_s',2, ...
    'lite_gnss_correction_tau_s',0.1, ...
    'lite_velocity_aiding_enabled',false,'lite_velocity_aiding_gain_s2',4, ...
    'lite_velocity_aiding_tau_s',0.15,'lite_velocity_aiding_max_rate_deg_s',10, ...
    'lite_velocity_aiding_history_s',0.5,'lite_velocity_aiding_hold_s',0.5, ...
    'lite_max_innovation_rad',deg2rad(45),'lite_gravity_m_s2',9.788, ...
    'lite_magnetic_ned_gauss',[0.22;0;0.43], ...
    'navigation_mode',"ideal",'navigation_warmup_s',15, ...
    'navigation_seed',62001,'navigation_origin',[47.397742;8.545594;488], ...
    'accelerometer_noise_std_m_s2',0.03,'accelerometer_bias_m_s2',[0.04;-0.03;0.06], ...
    'gyro_bias_deg_s',[0.03;-0.02;0.04],'gnss_hz',5,'gnss_delay_s',0.1, ...
    'gnss_position_std_m',[0.5;0.5;0.8],'gnss_position_bias_m',[0.2;-0.15;0.3],'gnss_velocity_std_m_s',0.1, ...
    'barometer_hz',50,'barometer_delay_s',0.03,'barometer_noise_std_m',0.3,'barometer_bias_m',0.4, ...
    'magnetometer_hz',50,'magnetometer_delay_s',0.01,'magnetometer_noise_std_gauss',0.003, ...
    'magnetometer_bias_gauss',[0.001;-0.001;0.002], ...
    'actuator_tau_variation_enabled',false,'actuator_tau_variation_fraction',0.15, ...
    'actuator_tau_variation_period_s',[11;13;17;19;23;29], ...
    'actuator_tau_variation_phase_rad',[0;0.7;1.4;2.1;2.8;3.5]);
for field=reshape(string(fieldnames(defaults)),1,[])
    if ~isfield(cfg,field), cfg.(field)=defaults.(field); end
end
end
