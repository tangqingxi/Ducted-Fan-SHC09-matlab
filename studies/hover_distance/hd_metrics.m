function m=hd_metrics(L,ref,plan,seed)
% 估计域为主、真值并列；固定窗口评价扰动偏差、偏航代价及恢复，不作事后对齐。
p=plan.hover_distance;t=L.time_s;q=t>=p.main_window_s(1)&t<p.main_window_s(2);
control=L.control_updated;qc=q&control;dt=1/400;count=sum(qc);
estimated=L.estimated_position-ref.position_ned_m;actual=L.position-ref.position_ned_m;
distance=vecnorm(estimated(:,1:2),2,2);true_distance=vecnorm(actual(:,1:2),2,2);
roll=rad2deg(L.estimated_euler(:,1));true_roll=rad2deg(L.euler(:,1));
yaw_rate=rad2deg(L.measured_omega(:,3)-ref.omega_body_rad_s(:,3));
true_yaw_rate=rad2deg(L.omega(:,3)-ref.omega_body_rad_s(:,3));
normal=L.mode==0&isfinite(L.lambda);scaled=normal&L.lambda<1-p.precheck.lambda_tolerance;
active=scaled(qc);minimum=min(L.lambda(qc&normal),[],'omitnan');if isempty(minimum),minimum=NaN;end
main_indices=find(q);changes=rad2deg(diff(L.actual_delta(main_indices,:)));
pwm=L.pwm_time>=p.main_window_s(1)&L.pwm_time<p.main_window_s(2);
source=min(numel(t),2*floor(L.pwm_time*400+1e-8)+1);pwm_scaled=scaled(source);
pwm_steps=rad2deg(diff(L.pwm_command));pwm_destination=pwm(2:end);
tilt=acosd(min(1,max(-1,cos(L.euler(:,1)).*cos(L.euler(:,2)))));
m=struct('method',string(L.name),'seed',seed,'main_samples',sum(q),'main_control_samples',count, ...
    'horizontal_rmse_m',sqrt(mean(distance(q).^2)),'horizontal_peak_m',max(distance(q)), ...
    'roll_rmse_deg',sqrt(mean(roll(q).^2)),'roll_peak_deg',max(abs(roll(q))), ...
    'true_horizontal_rmse_m',sqrt(mean(true_distance(q).^2)),'true_horizontal_peak_m',max(true_distance(q)), ...
    'true_roll_rmse_deg',sqrt(mean(true_roll(q).^2)),'true_roll_peak_deg',max(abs(true_roll(q))), ...
    'yaw_rate_rmse_deg_s',sqrt(mean(yaw_rate(q).^2)),'true_yaw_rate_rmse_deg_s',sqrt(mean(true_yaw_rate(q).^2)), ...
    'rate_loop_yaw_rmse_deg_s',rad2deg(sqrt(mean((L.measured_omega(q,3)-L.omega_sp(q,3)).^2))), ...
    'lambda_scaled_duration_s',sum(active)*dt,'lambda_scaled_duty',sum(active)/count, ...
    'lambda_longest_episode_s',longest(active)*dt,'normal_lambda_min',minimum, ...
    'mode1_duration_s',sum(L.mode(qc)==1)*dt,'mode1_duty',mean(L.mode(qc)==1), ...
    'mode2_duration_s',sum(L.mode(qc)==2)*dt,'mode2_duty',mean(L.mode(qc)==2), ...
    'whole_scaled_duty',mean(scaled(control)),'whole_mode1_duty',mean(L.mode(control)==1), ...
    'whole_mode2_duty',mean(L.mode(control)==2),'pwm_scaled_events',sum(pwm_scaled(pwm)), ...
    'actual_servo_rate_rms_deg_s',sqrt(mean((changes*800).^2,'all')), ...
    'actual_servo_travel_deg',sum(abs(changes),'all'),'pwm_step_rms_deg',sqrt(mean(pwm_steps(pwm_destination,:).^2,'all')), ...
    'solve_mean_ms',1000*mean(L.solve_time_s(control)),'actual_tilt_peak_deg',max(tilt), ...
    'aero_domain_failures',sum(L.aero_outside),'whole_estimated_horizontal_peak_m',max(distance), ...
    'whole_true_horizontal_peak_m',max(true_distance),'whole_altitude_peak_m',max(abs(actual(:,3))), ...
    'finite_states',all(isfinite([L.position,L.velocity,L.euler,L.omega,L.estimated_position,L.measured_omega]),'all'), ...
    'completed_40s',numel(t)==32001&&t(end)==40,'elapsed_s',L.elapsed_s);
recovery=t>=22&t<32;ix=find(recovery);speed=vecnorm(L.estimated_velocity(:,1:2),2,2);r=p.recovery;
settled=distance(ix)<=r.position_radius_m&speed(ix)<=r.speed_radius_m_s&abs(roll(ix))<=r.roll_radius_deg;
edges=diff([false;settled;false]);starts=find(edges==1);lengths=find(edges==-1)-starts;qualifying=find(lengths>=r.hold_s*800,1);
m.recovery_entry_s=NaN;m.recovery_confirmed_s=NaN;m.recovery_not_reached=isempty(qualifying);
if ~isempty(qualifying),m.recovery_entry_s=t(ix(starts(qualifying)))-22;m.recovery_confirmed_s=m.recovery_entry_s+r.hold_s;end
m.recovery_horizontal_peak_m=max(distance(recovery));m.recovery_roll_peak_deg=max(abs(roll(recovery)));
initial=estimated(ix(1),1:2);m.recovery_opposite_position_overshoot_m=NaN;
if norm(initial)>1e-6,m.recovery_opposite_position_overshoot_m=max(0,-min(estimated(ix,1:2)*initial'/norm(initial)));end
m.recovery_opposite_roll_overshoot_deg=max(0,-min(sign(roll(ix(1)))*roll(ix)));
b=t>=4&t<10;m.preload_horizontal_rmse_m=sqrt(mean(distance(b).^2));
% 有效性与宽松悬停健康检查分开，不能把数据完整说成跟踪任务合格。
gate=p.precheck;
m.valid_data=m.finite_states&&m.completed_40s&&m.aero_domain_failures==0;
m.hover_healthy=m.valid_data&&m.horizontal_rmse_m<=gate.estimated_horizontal_rmse_max_m ...
    &&m.horizontal_peak_m<=gate.estimated_horizontal_peak_max_m&&m.whole_true_horizontal_peak_m<=gate.true_horizontal_peak_max_m ...
    &&m.whole_altitude_peak_m<=gate.altitude_peak_max_m&&m.actual_tilt_peak_deg<=gate.tilt_peak_max_deg;
m.lambda_target_passed=m.lambda_scaled_duty>=gate.normal_scaled_duty_min&&m.lambda_scaled_duty<=gate.normal_scaled_duty_max ...
    &&m.normal_lambda_min>=gate.normal_lambda_min_lower&&m.normal_lambda_min<=gate.normal_lambda_min_upper&&m.mode1_duty<=gate.mode1_duty_max;
m.precheck_passed=m.hover_healthy;
if string(L.name)=="EXAMPLE_PINV",m.precheck_passed=m.precheck_passed&&m.yaw_rate_rmse_deg_s<=gate.pinv_yaw_rate_rmse_max_deg_s;
elseif string(L.name)=="PCA_PREDICTIVE",m.precheck_passed=m.precheck_passed&&m.lambda_target_passed;end
end

function n=longest(active)
% 400Hz判定样本的连续段长，窗口右端不重复计时。
edges=diff([false;active(:);false]);n=max([0;find(edges==-1)-find(edges==1)]);
end
