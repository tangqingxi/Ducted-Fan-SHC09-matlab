function entries = registry()
% 唯一分配器注册表；显式句柄保证可复现，新增方法只增加一项。
entries=[entry('DA_NS','da_ns',@da_ns_allocate,@da_ns_manifest), ...
 entry('WLS','wls',@wls_allocate,@wls_manifest), ...
 entry('DCA','dca',@dca_allocate,@dca_manifest), ...
 entry('PCA_STATIC','pca_static',@pca_static_allocate,@pca_static_manifest), ...
 entry('PCA_PREDICTIVE','pca_predictive',@pca_predictive_allocate,@pca_predictive_manifest), ...
 entry('EXAMPLE_PINV','example_pinv',@example_pinv_allocate,@example_pinv_manifest)];
end
function value=entry(name,directory,allocate,manifest)
% 文件使用插件名前缀，避免无package目录时函数同名。
value=struct('name',string(name),'directory',['allocators/',directory],'allocate',allocate,'manifest',manifest);
end
