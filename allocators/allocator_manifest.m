function m = allocator_manifest(name,requires,priority)
% 公共清单结构；最大耗时是桌面观测预算，不作为物理延迟或硬截止。
m=struct('name',string(name),'version',"1.0.0",'requires',string(requires), ...
 'info_fields',["allocated_effect","iterations","exitflag","mode"], ...
 'supports',struct('actuator_count',6,'virtual_dimension',3,'priority_demand',priority,'deterministic',true), ...
 'max_solve_time_s',1/800);
end
