function [metrics,states]=ppid_evaluate(L,ref,seed,plan)
% 对象真值只在离线评价使用；新任务门槛在首次伪逆开发前声明，不改旧F8门槛。
t=L.time_s;q=t>=6&t<=50;position=L.position-ref.position_ned_m;
yaw=atan2(sin(L.euler(:,3)-ref.euler_rad(:,3)),cos(L.euler(:,3)-ref.euler_rad(:,3)));
horizontal=vecnorm(position(q,1:2),2,2);change=rad2deg(diff(L.actual_delta(q,:)));
metrics=struct('method',string(L.name),'seed',seed, ...
    'horizontal_rmse_m',sqrt(mean(horizontal.^2)),'horizontal_peak_m',max(horizontal), ...
    'altitude_rmse_m',sqrt(mean(position(q,3).^2)),'altitude_peak_m',max(abs(position(q,3))), ...
    'yaw_rmse_deg',rad2deg(sqrt(mean(yaw(q).^2))),'yaw_peak_deg',rad2deg(max(abs(yaw(q)))), ...
    'actual_tilt_peak_deg',max(acosd(min(1,max(-1,cos(L.euler(:,1)).*cos(L.euler(:,2)))))), ...
    'actual_servo_rate_rms_deg_s',sqrt(mean((change*800).^2,'all')), ...
    'actual_servo_travel_deg',sum(abs(change),'all'), ...
    'pwm_step_rms_deg',sqrt(mean(rad2deg(diff(L.pwm_command)).^2,'all')), ...
    'estimator_attitude_rms_deg',rad2deg(sqrt(mean(L.estimate_attitude_error_rad(q).^2))), ...
    'estimated_position_rmse_m',sqrt(mean(sum((L.estimated_position(q,:)-L.position(q,:)).^2,2))), ...
    'raw_navigation_position_rmse_m',sqrt(mean(sum((L.raw_navigation_position(q,:)-L.position(q,:)).^2,2))), ...
    'aero_domain_failures',sum(L.aero_outside),'elapsed_s',L.elapsed_s, ...
    'rate_control_updates',sum(L.control_updated),'ekf_main_updates',L.ekf_main_updates, ...
    'lambda_min_task',min(L.lambda(q),[],'omitnan'),'scaled_duration_s',sum(L.lambda(q)<1-1e-6&L.mode(q)==0)/800, ...
    'fallback_samples_task',sum(L.mode(q)~=0),'solve_mean_s',mean(L.solve_time_s(L.control_updated)));
if isempty(metrics.lambda_min_task),metrics.lambda_min_task=NaN;end
pass=true;
for field=string(fieldnames(plan.acceptance))'
    if field=="role",continue;end
    pass=pass&&metrics.(field)<=plan.acceptance.(field);
end
metrics.task_passed=pass&&all(isfinite([L.position,L.velocity,L.euler,L.omega]),'all');
actual=[L.position,L.velocity,rad2deg(L.euler),rad2deg(L.omega)];
target=[ref.position_ned_m,ref.velocity_ned_m_s,rad2deg(ref.euler_rad),rad2deg(ref.omega_body_rad_s)];
error=actual-target;error(:,7:9)=rad2deg(atan2(sin(deg2rad(error(:,7:9))),cos(deg2rad(error(:,7:9)))));
names=["x","y","z","vx","vy","vz","roll","pitch","yaw","p","q","r"];
windows=[0,52;6,50;10,46;0,6];labels=["whole","task","cruise","initial_hover"];states=table();
for w=1:4
    mask=t>=windows(w,1)&t<=windows(w,2);
    for j=1:12
        states=[states;table(string(L.name),seed,labels(w),names(j),sqrt(mean(error(mask,j).^2)),max(abs(error(mask,j))), ...
            'VariableNames',{'method','seed','window','state','rmse','peak_abs'})]; %#ok<AGROW>
    end
end
end
