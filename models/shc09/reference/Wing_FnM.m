function y=Wing_FnM(Vvw,AOA,Wing_Config)

%----------------------------------------------------
%计算机翼力与力矩
%输入空速Vvw，迎角AOA
%输出升力、阻力相关气动力标量 y(1), y(2)，以及绕机体 x 轴的俯仰力矩 y(3)
%机翼力计算公式：
%L_c为升力，D_c为阻力，M_m为俯仰力矩
%
%----------------------------------------------------
%初始化

    wl = Wing_Config.wl;
    wd = Wing_Config.wd;
    wm = Wing_Config.wm;

%----------------------------------------------------
%升力相关项、阻力相关项、绕机体 x 轴的俯仰力矩

    y(1) = Vvw^2*ppval(wl,AOA);
    y(2) = Vvw^2*ppval(wd,AOA);
    y(3) = Vvw^2*ppval(wm,AOA);

%----------------------------------------------------

end
